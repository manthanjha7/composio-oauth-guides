import Link from "next/link";
import { DifficultyBadge, ManagedBadge, OriginBadge, difficultyRange } from "@/components/badges";
import { GenerateBox } from "@/components/GenerateBox";
import { listGuides } from "@/lib/store";

// Lists change whenever the agent saves a new guide.
export const dynamic = "force-dynamic";

export default async function Home() {
  const guides = await listGuides();
  const seeds = guides.filter((g) => g.meta.origin === "seed");
  const live = guides.filter((g) => g.meta.origin === "live").sort((a, b) => b.meta.generated_at.localeCompare(a.meta.generated_at));

  return (
    <div className="space-y-10">
      <section className="space-y-4">
        <h1 className="text-3xl font-semibold tracking-tight">Will your OAuth app take an hour, or six weeks and a security audit?</h1>
        <p className="max-w-3xl text-stone-600">
          Your agent&apos;s users connect their Gmail, Slack or Shopify through an OAuth app. Composio&apos;s managed apps get you started, but production
          (your own name on the consent screen, your own quota, extra scopes) or a bring-your-own app means creating one and getting it approved. Each guide
          tells you <b>if you need your own app</b>, <b>how hard it is for your scenario</b>, <b>your hands-on time vs. time waiting on the provider</b>,{" "}
          <b>what blocks approval</b>, and <b>which steps an agent can do for you</b>. Every claim is labelled with its evidence.
        </p>
        <GenerateBox examples={["Calendly", "HubSpot", "Xero", "Zoom"]} />
      </section>

      <section>
        <h2 className="mb-3 text-lg font-semibold">Library</h2>
        <GuideGrid guides={seeds} />
      </section>

      {live.length > 0 && (
        <section>
          <h2 className="mb-1 text-lg font-semibold">Generated by the agent</h2>
          <p className="mb-3 text-sm text-stone-500">Created live from the box above. Not yet reviewed by a human; check the evidence labels.</p>
          <GuideGrid guides={live} />
        </section>
      )}
    </div>
  );
}

function GuideGrid({ guides }: { guides: Awaited<ReturnType<typeof listGuides>> }) {
  if (guides.length === 0) return <p className="text-sm text-stone-500">No guides yet.</p>;
  return (
    <div className="grid gap-3 sm:grid-cols-2">
      {guides.map((r) => {
        const hardest = [...r.guide.scenarios].sort((a, b) => ["easy", "medium", "hard", "unknown"].indexOf(b.difficulty) - ["easy", "medium", "hard", "unknown"].indexOf(a.difficulty))[0];
        return (
          <Link key={r.slug} href={`/guides/${r.slug}`} className="group rounded-xl border border-stone-200 bg-white p-4 shadow-sm transition hover:border-violet-300 hover:shadow">
            <div className="flex items-start justify-between gap-2">
              <h3 className="font-semibold group-hover:text-violet-700">{r.guide.app.name}</h3>
              <DifficultyBadge level={difficultyRange(r)} />
            </div>
            <p className="mt-1 line-clamp-3 text-sm text-stone-600">{r.guide.summary}</p>
            <div className="mt-3 flex flex-wrap items-center gap-1.5">
              <ManagedBadge managed={r.guide.composio.managed_oauth} />
              <OriginBadge record={r} />
            </div>
            <dl className="mt-3 grid grid-cols-2 gap-2 text-xs text-stone-600">
              <div>
                <dt className="text-stone-400">Scenarios</dt>
                <dd className="font-medium text-stone-800">{r.guide.scenarios.length} · {r.guide.claims.length} evidenced claims</dd>
              </div>
              <div>
                <dt className="text-stone-400">Worst-case wait</dt>
                <dd className="font-medium text-stone-800">{hardest?.waiting.estimate ?? "Unknown"}</dd>
              </div>
            </dl>
          </Link>
        );
      })}
    </div>
  );
}
