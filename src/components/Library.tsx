"use client";

import Link from "next/link";
import { useMemo, useState } from "react";
import { Badge, DifficultyBadge, ManagedBadge, ScenarioDots, type Tone } from "./badges";

export interface CardData {
  slug: string;
  name: string;
  summary: string;
  managed: string;
  origin: "seed" | "live";
  reviewed: boolean;
  range: string;
  scenarios: number;
  claims: number;
  verified: string;
  worstWait: string;
  hardestLabel: string;
  hardestLevel: string;
  levels: string[];
  date: string;
}

const FILTERS = [
  { id: "all", label: "All" },
  { id: "managed", label: "Composio managed" },
  { id: "byo", label: "Bring your own" },
  { id: "hard", label: "Has a hard path" },
] as const;

export function Library({ cards }: { cards: CardData[] }) {
  const [q, setQ] = useState("");
  const [filter, setFilter] = useState<(typeof FILTERS)[number]["id"]>("all");
  const shown = useMemo(() => {
    const term = q.trim().toLowerCase();
    return cards.filter((c) => {
      if (term && !`${c.name} ${c.summary}`.toLowerCase().includes(term)) return false;
      if (filter === "managed") return c.managed === "yes";
      if (filter === "byo") return c.managed !== "yes";
      if (filter === "hard") return c.range.endsWith("hard");
      return true;
    });
  }, [cards, q, filter]);
  const seeds = shown.filter((c) => c.origin === "seed");
  const live = shown.filter((c) => c.origin === "live");

  return (
    <div className="space-y-10">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div role="group" aria-label="Filter guides" className="scrollbar-none -mx-1 flex gap-1.5 overflow-x-auto px-1">
          {FILTERS.map((f) => (
            <button
              key={f.id}
              onClick={() => setFilter(f.id)}
              aria-pressed={filter === f.id}
              className={`whitespace-nowrap rounded-full px-3 py-1.5 text-sm ring-1 ring-inset transition ${
                filter === f.id ? "bg-ink text-bg ring-ink" : "text-muted ring-line-strong hover:text-ink"
              }`}
            >
              {f.label}
            </button>
          ))}
        </div>
        <label className="relative block sm:w-64">
          <span className="sr-only">Search guides</span>
          <input
            value={q}
            onChange={(e) => setQ(e.target.value)}
            placeholder="Search guides"
            className="w-full rounded-lg border border-line bg-surface px-3 py-1.5 text-sm text-ink placeholder:text-faint outline-none focus:border-accent/60"
          />
        </label>
      </div>

      <Group title="Library" subtitle="Seed guides, researched under the same evidence rules and quote-checked against live pages." cards={seeds} empty="No library guides match." />
      <Group
        title="Generated by the agent"
        subtitle="Created live from the box above. Not yet reviewed by a human, so lean on the evidence labels."
        cards={live}
        empty={cards.some((c) => c.origin === "live") ? "No generated guides match." : "Nothing generated yet. Try the box above."}
        generated
      />
    </div>
  );
}

function Group({ title, subtitle, cards, empty, generated }: { title: string; subtitle: string; cards: CardData[]; empty: string; generated?: boolean }) {
  return (
    <section aria-labelledby={`h-${title}`}>
      <div className="mb-4 flex items-baseline justify-between gap-3">
        <div>
          <h2 id={`h-${title}`} className="text-lg font-semibold tracking-tight">
            {title} <span className="ml-1 font-mono text-sm font-normal text-faint">{cards.length}</span>
          </h2>
          <p className="text-sm text-muted">{subtitle}</p>
        </div>
      </div>
      {cards.length === 0 ? (
        <p className="rounded-xl border border-dashed border-line-strong p-6 text-center text-sm text-faint">{empty}</p>
      ) : (
        <div className="grid gap-3 md:grid-cols-2">
          {cards.map((c) => (
            <GuideCard key={c.slug} c={c} generated={generated} />
          ))}
        </div>
      )}
    </section>
  );
}

function GuideCard({ c, generated }: { c: CardData; generated?: boolean }) {
  const origin: [string, Tone] = c.reviewed
    ? ["Human-reviewed", "good"]
    : generated
      ? ["Agent-generated · not human-reviewed", "warn"]
      : ["Seed guide · review pending", "info"];
  return (
    <Link
      href={`/guides/${c.slug}`}
      className={`group flex flex-col rounded-xl border bg-surface p-5 transition hover:-translate-y-px hover:border-accent/50 hover:bg-surface-2 ${
        generated ? "border-dashed border-line-strong" : "border-line"
      }`}
    >
      <div className="flex items-start justify-between gap-3">
        <div className="min-w-0">
          <h3 className="truncate text-base font-semibold group-hover:text-accent">
            {c.name}
            {generated && <span className="ml-2 font-mono text-xs font-normal text-faint">agent · {c.date}</span>}
          </h3>
        </div>
        <div className="flex shrink-0 items-center gap-2">
          <span className="hidden text-xs text-muted sm:inline">{c.range === "unknown" ? "Unknown" : c.range.split("–").map((x) => x[0].toUpperCase() + x.slice(1)).join(" → ")}</span>
          <ScenarioDots levels={c.levels} />
        </div>
      </div>
      <p className="mt-2 line-clamp-3 text-sm leading-relaxed text-muted">{c.summary}</p>
      <div className="mt-3 flex flex-wrap gap-1.5">
        <ManagedBadge managed={c.managed} />
        <Badge tone={origin[1]}>{origin[0]}</Badge>
      </div>
      <dl className="mt-4 grid grid-cols-[auto_1fr] gap-x-4 gap-y-1.5 border-t border-line pt-3 text-xs">
        <dt className="text-faint">Hardest path</dt>
        <dd className="flex min-w-0 flex-wrap items-center gap-x-2 gap-y-1">
          <DifficultyBadge level={c.hardestLevel} />
          <span className="min-w-0 text-ink/90">{c.hardestLabel}</span>
        </dd>
        <dt className="text-faint">Worst-case wait</dt>
        <dd className="text-ink/90">{c.worstWait}</dd>
        <dt className="text-faint">Evidence</dt>
        <dd className="font-mono text-muted">
          {c.scenarios} scenarios · {c.claims} claims · {c.verified} quotes verified
        </dd>
      </dl>
    </Link>
  );
}
