import { LABEL_INFO } from "./evidence";
import { appliesTo, CHECK_INFO, PATH_INFO, pathLabel } from "./guide-view";
import type { ClaimT, GuideRecord } from "./schema";

const OWNER = { agent: "🤖 Agent can do", you: "👤 You", waiting: "⏳ Waiting on provider" } as const;
const MANAGED: Record<string, string> = {
  yes: "Composio has a managed app for this (fine for prototypes).",
  no: "No Composio-managed app: bring your own.",
  not_in_composio: "Not in Composio's catalog.",
  unknown: "Composio status unknown.",
};
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);

/** Plain Markdown version of a guide: for docs, tickets, or a coding agent. `scenarioId` narrows the steps to one setup. */
export function guideToMarkdown(r: GuideRecord, baseUrl: string, scenarioId?: string | null): string {
  const g = r.guide;
  const names = new Map(g.scenarios.map((s) => [s.id, s.label]));
  const selected = g.scenarios.find((s) => s.id === scenarioId) ?? null;
  const t = (text: string) => text.replace(/\b(s\d+)\b/g, (m) => (names.has(m) ? `"${names.get(m)}"` : m));
  const cite = (ids: string[]) => {
    const list = [...new Set(ids)].filter((id) => g.claims.some((c) => c.id === id));
    return list.length ? ` [${list.join(", ")}]` : "";
  };
  const name = g.app.name.replace(/\s*\(.*\)\s*$/, "") || g.app.name;
  const v = r.meta.verification;
  const labels = (Object.keys(LABEL_INFO) as ClaimT["label"][]).filter((k) => g.claims.some((c) => c.label === k));
  const url = `${baseUrl}/guides/${r.slug}${selected ? `?s=${selected.id}` : ""}`;

  const L: string[] = [];
  L.push(`# ${name}: OAuth app setup`);
  L.push("");
  L.push(
    `> ${r.meta.origin === "seed" ? "Library guide" : "Generated by the agent"} · ${r.meta.reviewed ? "human-reviewed" : "not human-reviewed"} · researched ${r.meta.generated_at.slice(0, 10)} · ${v.quotes_verified}/${v.quotes_checked} quotes verified · ${url}`,
  );
  if (r.meta.partial) L.push(">", "> **Incomplete:** research timed out; some sections may be thin.");
  (r.meta.warnings ?? []).forEach((w) => L.push(">", `> **Note:** ${w}`));
  L.push("", `Evidence labels: ${labels.map((k) => `${LABEL_INFO[k].icon} ${LABEL_INFO[k].name}`).join(" · ")}. Citations like [c3] point to the Evidence section.`, "");
  if (g.verdict) L.push(`**${t(g.verdict)}**`, "");
  L.push(t(g.summary), "");
  L.push(`**Composio:** ${MANAGED[g.composio.managed_oauth] ?? MANAGED.unknown} ${g.composio.note}`);
  if (g.composio.credential_guide_url) L.push(`Composio setup guide: ${g.composio.credential_guide_url}`);
  L.push("", "## Do you need your own OAuth app?", t(g.need_own_app.answer));
  g.need_own_app.reasons.forEach((x) => L.push(`- ${t(x)}`));

  L.push("", "## Setups", "| Setup | Difficulty | Your time | Provider wait | Approval |", "|---|---|---|---|---|");
  g.scenarios.forEach((s) =>
    L.push(`| ${s.id === selected?.id ? "▶ " : ""}**${s.label}**: ${t(s.when_this_applies)} | ${cap(s.difficulty)} | ${s.hands_on.estimate} | ${s.waiting.estimate} | ${t(s.approval)}${cite(s.claim_ids)} |`),
  );

  if (selected) {
    L.push("", `## Your setup: ${selected.label}`);
    if (selected.path) L.push(`- **${pathLabel(selected)}:** ${PATH_INFO[selected.path].meaning}.`);
    if (selected.review_checks?.length) L.push(`- **The review checks:** ${selected.review_checks.map((c) => CHECK_INFO[c]).join(", ")}.`);
    if (selected.shortcut) L.push(`- **Shortcut:** ${t(selected.shortcut)}`);
    (selected.extras ?? []).forEach((x) => L.push(`- ${t(x)}`));
  }
  // With a setup chosen, only the items that apply to it.
  const keep = <T extends { scenario_ids?: string[] }>(xs: T[]) => (selected ? xs.filter((x) => appliesTo(x.scenario_ids, selected.id)) : xs);
  const prereqs = keep(g.prerequisites);
  const traps = keep(g.traps);
  const blockers = keep(g.blockers);

  if (prereqs.length) {
    L.push("", "## Before you start");
    prereqs.forEach((p) => L.push(`- **${t(p.title)}**: ${t(p.detail)}${cite(p.claim_ids)}`));
  }

  const steps = selected ? g.steps.filter((s) => appliesTo(s.scenario_ids, selected.id)) : g.steps;
  L.push("", selected ? `## Steps for: ${selected.label}` : "## Steps");
  steps.forEach((s, i) => {
    const only = !selected && s.scenario_ids.length ? ` _(only: ${s.scenario_ids.map((id) => names.get(id) ?? id).join("; ")})_` : "";
    L.push(`${i + 1}. **${t(s.title)}** · ${OWNER[s.owner]}${only}`);
    L.push(`   ${t(s.detail)}${cite(s.claim_ids)}`);
    if (s.inputs.length) L.push(`   - Needs: ${s.inputs.map(t).join("; ")}`);
    L.push(`   - Done when: ${t(s.done_when)}`);
    if (s.link) L.push(`   - ${s.link}`);
  });

  if (traps.length) {
    L.push("", "## Traps");
    traps.forEach((x) => L.push(`- **${t(x.title)}**: ${t(x.detail)}${cite(x.claim_ids)}`));
  }
  if (blockers.length) {
    L.push("", "## Stuck?");
    blockers.forEach((b) => L.push(`- **${t(b.symptom)}**: ${t(b.what_it_means)} → ${t(b.what_to_do)}${b.agent_can_help ? ` (🤖 ${t(b.agent_can_help)})` : ""}${cite(b.claim_ids)}`));
  }
  if (g.open_questions.length) {
    L.push("", "## Unconfirmed");
    g.open_questions.forEach((q) => L.push(`- ${t(q)}`));
  }

  L.push("", "## Evidence");
  g.claims.forEach((c) => {
    const info = LABEL_INFO[c.label];
    L.push(`- **${c.id}** ${info.icon} ${info.name}: ${c.text}${c.source_url ? ` (${c.source_url})` : ""}${c.quote ? `\n  > "${c.quote}"` : ""}${c.note ? `\n  _${c.note}_` : ""}`);
  });
  if (r.meta.probes.length) {
    L.push("", "## Endpoint checks");
    r.meta.probes.forEach((p) => L.push(`- ${p.id}: GET ${p.url} → ${p.status ?? "no response"}. ${p.observation.slice(0, 200)}`));
  }
  return L.join("\n") + "\n";
}
